CREATE TABLE IF NOT EXISTS rap_programas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 120)
);
CREATE UNIQUE INDEX IF NOT EXISTS rap_programas_nombre_unico
    ON rap_programas (lower(btrim(nombre)));

CREATE TABLE IF NOT EXISTS rap_programa_asignaturas (
    programa_id bigint NOT NULL REFERENCES rap_programas(id),
    alfa text NOT NULL CHECK (alfa <> '' AND alfa = upper(btrim(alfa))),
    PRIMARY KEY (programa_id, alfa)
);

ALTER TABLE estudiantes
    ADD COLUMN IF NOT EXISTS rap_programa_id bigint REFERENCES rap_programas(id),
    ADD COLUMN IF NOT EXISTS rap_registrado_en timestamptz,
    ADD COLUMN IF NOT EXISTS estado_matriz text,
    ADD COLUMN IF NOT EXISTS observaciones text;
ALTER TABLE estudiantes ALTER COLUMN rap_registrado_en SET DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE profesores
    ADD COLUMN IF NOT EXISTS programa text,
    ADD COLUMN IF NOT EXISTS asignaturas text,
    ADD COLUMN IF NOT EXISTS horas_dedicacion integer,
    ADD COLUMN IF NOT EXISTS observaciones text;
